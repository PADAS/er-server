# ── Fixtures ──────────────────────────────────────────────────────────────


@dataclass
class FakeRevision:
    """Lightweight stand-in for a revision row.

    The classifier never touches anything beyond ``sequence``, ``action``,
    and ``data`` — using a dataclass keeps the unit tests independent of
    the revision system's autogenerated model.
    """

    sequence: int
    action: str
    data: dict[str, Any]


def _v1_schema(marker: str = "v1") -> str:
    return f'{{"schema": {{"marker": "{marker}"}}}}'


def _v2_schema(marker: str = "v2") -> str:
    return f'{{"json": {{"marker": "{marker}"}}, "ui": {{"fields": {{}}}}}}'


def _classify_revisions(
    *,
    event_type_value: str,
    revisions: list[FakeRevision],
) -> RepairClassification:
    """Test helper: build a history and run the pure classifier.

    Mirrors the ergonomics of the previous private
    ``_classify_from_revisions`` helper while exercising the real
    public API (``classify(history)``).
    """
    history = EventTypeRevisionHistory.from_revisions(
        event_type_value=event_type_value,
        event_type_id=str(uuid4()),
        revisions=revisions,
    )
    return classify(history)


# ── Pure classifier tests (no DB) ─────────────────────────────────────────


class TestClassifierPure:
    """Unit tests for the pure classification logic."""

    def test_no_migration_revision_classifies_as_not_migrated(self):
        result = _classify_revisions(
            event_type_value="never_v1",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v2_schema(), "version": "2"}),
                FakeRevision(2, ACTION_UPDATED, {"display": "Renamed"}),
            ],
        )
        assert result.strategy == RepairStrategy.NOT_MIGRATED
        assert result.migration_revision_sequence is None
        assert result.reconstructed_v1_schema is None

    def test_only_version_changed_is_not_a_migration_revision(self):
        """A revision flipping only ``version`` (without touching ``schema``)
        is not the migration fingerprint and must not be misdetected.
        """
        result = _classify_revisions(
            event_type_value="version_only_flip",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v1_schema(), "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.NOT_MIGRATED

    def test_only_schema_changed_is_not_a_migration_revision(self):
        """A revision changing only ``schema`` (without ``version``) is a
        regular schema edit, not a migration."""
        result = _classify_revisions(
            event_type_value="schema_only_edit",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v1_schema(), "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v1_schema("v1b")}),
            ],
        )
        assert result.strategy == RepairStrategy.NOT_MIGRATED

    def test_rebuild_from_v1_when_v1_reconstructable_and_no_post_edits(self):
        v1 = _v1_schema()
        result = _classify_revisions(
            event_type_value="happy_path",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": v1, "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"display": "Renamed"}),
                FakeRevision(3, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.REBUILD_FROM_V1
        assert result.migration_revision_sequence == 3
        assert result.reconstructed_v1_schema == v1
        assert result.post_migration_schema_edits == 0

    def test_rebuild_from_v1_replays_intermediate_v1_schema_edits(self):
        v1_initial = _v1_schema("initial")
        v1_final = _v1_schema("final")
        result = _classify_revisions(
            event_type_value="replay_chain",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": v1_initial, "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v1_schema("middle")}),
                FakeRevision(3, ACTION_UPDATED, {"schema": v1_final}),
                FakeRevision(4, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.REBUILD_FROM_V1
        # The most recent V1 schema before migration is the one we re-migrate.
        assert result.reconstructed_v1_schema == v1_final

    def test_skip_user_edited_when_post_migration_schema_was_edited(self):
        result = _classify_revisions(
            event_type_value="user_edited",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v1_schema(), "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
                FakeRevision(3, ACTION_UPDATED, {"schema": _v2_schema("user-edit")}),
            ],
        )
        assert result.strategy == RepairStrategy.SKIP_USER_EDITED
        assert result.migration_revision_sequence == 2
        assert result.post_migration_schema_edits == 1
        # Even if reconstruction would have succeeded, SKIP_USER_EDITED
        # wins to respect the user.
        assert result.reconstructed_v1_schema is None

    def test_skip_user_edited_counts_multiple_post_migration_edits(self):
        result = _classify_revisions(
            event_type_value="multi_edit",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v1_schema(), "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
                FakeRevision(3, ACTION_UPDATED, {"schema": _v2_schema("e1")}),
                FakeRevision(4, ACTION_UPDATED, {"display": "renamed"}),  # not a schema edit
                FakeRevision(5, ACTION_UPDATED, {"schema": _v2_schema("e2")}),
            ],
        )
        assert result.strategy == RepairStrategy.SKIP_USER_EDITED
        assert result.post_migration_schema_edits == 2

    def test_reconstruct_from_json_when_snapshot_lacks_schema_field(self):
        """Snapshot revisions are full but in old data the 'schema' key may
        be absent (e.g. truncated/legacy export). Reconstruction from V1
        is not possible — fall through to RECONSTRUCT_FROM_JSON."""
        result = _classify_revisions(
            event_type_value="snapshot_no_schema",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"display": "No schema in snapshot"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.RECONSTRUCT_FROM_JSON
        assert result.reconstructed_v1_schema is None
        assert any("snapshot" in note.lower() for note in result.notes)

    def test_reconstruct_from_json_when_no_creation_snapshot_revision(self):
        """If only updates exist (e.g. revisions were truncated), we cannot
        reconstruct V1."""
        result = _classify_revisions(
            event_type_value="no_snapshot",
            revisions=[
                FakeRevision(5, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.RECONSTRUCT_FROM_JSON

    def test_reconstruct_from_json_when_reconstruction_yields_empty_string(self):
        result = _classify_revisions(
            event_type_value="empty_v1",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": "", "version": "1"}),
                FakeRevision(2, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.RECONSTRUCT_FROM_JSON

    def test_unrelated_actions_do_not_affect_classification(self):
        """ACTION_DELETED / relation-deleted entries must be ignored."""
        result = _classify_revisions(
            event_type_value="with_delete_noise",
            revisions=[
                FakeRevision(1, ACTION_ADDED, {"schema": _v1_schema(), "version": "1"}),
                FakeRevision(2, ACTION_DELETED, {}),  # noise
                FakeRevision(3, ACTION_UPDATED, {"schema": _v2_schema(), "version": "2"}),
            ],
        )
        assert result.strategy == RepairStrategy.REBUILD_FROM_V1
        assert result.reconstructed_v1_schema == _v1_schema()


# ── Integration tests against the real revision system ───────────────────


@pytest.mark.django_db
@pytest.mark.usefixtures("tenant_settings", "das_tenant_monkeypatch")
class TestClassifyEventTypeIntegration:
    """Drive the classifier through the real ``RevisionMixin`` machinery."""

    def test_full_lifecycle_v1_to_v2_classifies_as_rebuild_from_v1(self):
        v1 = _v1_schema("integration")
        event_type = EventTypeFactory.create(
            value="integration_lifecycle",
            schema=v1,
            version=EventType.VersionChoices.VERSION_1,
        )
        # Migration: schema + version flip in a single save
        event_type.schema = _v2_schema("integration")
        event_type.version = EventType.VersionChoices.VERSION_2
        event_type.save()

        classification = classify_event_type(event_type)
        assert classification.strategy == RepairStrategy.REBUILD_FROM_V1
        assert classification.reconstructed_v1_schema == v1
        assert classification.post_migration_schema_edits == 0

    def test_post_migration_schema_edit_classifies_as_skip_user_edited(self):
        event_type = EventTypeFactory.create(
            value="integration_user_edit",
            schema=_v1_schema("ie"),
            version=EventType.VersionChoices.VERSION_1,
        )
        event_type.schema = _v2_schema("ie")
        event_type.version = EventType.VersionChoices.VERSION_2
        event_type.save()
        # Simulate a user touching the V2 schema after migration.
        event_type.schema = _v2_schema("user_modified")
        event_type.save()

        classification = classify_event_type(event_type)
        assert classification.strategy == RepairStrategy.SKIP_USER_EDITED
        assert classification.post_migration_schema_edits == 1


